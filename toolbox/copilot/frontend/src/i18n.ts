export type CopilotStringKey = keyof typeof strings;

export function readCopilotLocale(): CopilotLocale {
  const lang = typeof document !== "undefined" ? document.documentElement.lang : "zh";
  return lang.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function copilotT(locale: CopilotLocale, key: CopilotStringKey): string {
  return strings[key][locale] ?? strings[key].zh;
}
