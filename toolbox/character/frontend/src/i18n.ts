export type CharacterStringKey = keyof typeof strings;

export function readCharacterLocale(): CharacterLocale {
  const lang = typeof document !== "undefined" ? document.documentElement.lang : "zh";
  return lang.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function characterT(locale: CharacterLocale, key: CharacterStringKey): string {
  return strings[key][locale] ?? strings[key].zh;
}
